function showDepartmentDetails() {
    const container = document.getElementById("conditionsContainer");

    if (!container) return;

    const departmentId = document.body.dataset.department;

    const department = departments.find(item => item.id === departmentId);

    const title = document.getElementById("departmentTitle");

    if (!department) {
        if (title) title.textContent = "القسم غير موجود";
        container.innerHTML = "<p>لم يتم العثور على بيانات هذا القسم.</p>";
        return;
    }

    document.title = department.name + " | مستشفى الجامعة";

    if (title) {
        title.textContent = department.icon + " " + department.name;
    }

    container.innerHTML = department.conditions
        .map(createConditionCard)
        .join("");
}

document.addEventListener("DOMContentLoaded", function () {
    showDepartments();
    showDepartmentDetails();
});
