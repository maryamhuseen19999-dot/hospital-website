function createDepartmentCard(department) {
    return `
        <article class="department-card">
            <span class="department-icon">${department.icon}</span>
            <h3>${department.name}</h3>
            <p>${department.description}</p>
            <a href="${department.id}.html">ادخل إلى القسم ←</a>
        </article>
    `;
}

function showDepartments() {
    const grid = document.getElementById("departmentsGrid");

    if (!grid) return;

    grid.innerHTML = departments.map(createDepartmentCard).join("");

    const search = document.createElement("input");
    search.type = "search";
    search.placeholder = "ابحثي عن قسم طبي...";
    search.className = "department-search";
    search.setAttribute("aria-label", "البحث عن قسم طبي");

    grid.parentElement.insertBefore(search, grid);

    search.addEventListener("input", function () {
        const value = this.value.trim().toLowerCase();

        const filtered = departments.filter(department =>
            department.name.toLowerCase().includes(value) ||
            department.description.toLowerCase().includes(value)
        );

        grid.innerHTML = filtered.length
            ? filtered.map(createDepartmentCard).join("")
            : "<p>لا توجد أقسام مطابقة لبحثك</p>";
    });
}

